// Package samba renders the Samba configuration of Kinolune OS (DIST-018)
// from a few typed settings. Only the root helper (alpha-admin-priv) writes
// the result; the web daemon never sends configuration text, so it cannot
// smuggle directives like "root preexec" into smb.conf (see ADR-NNNN).
//
// The static /etc/samba/smb.conf ends its [global] section with
//
//	include = /etc/samba/smb.conf.d/kinolune.conf
//
// and the rendered file continues [global] with the guest policy, then
// defines the shares.
package samba

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Default paths in the image.
const (
	ConfPath     = "/etc/samba/smb.conf.d/kinolune.conf"
	SettingsPath = "/var/lib/alpha/samba/settings.json"
	ImportPath   = "/var/lib/alpha/samba/import.smbpasswd"
	MediaDir     = "/var/srv/media"
	UsersDir     = "/var/srv/users"
	TimeMachDir  = "/var/srv/timemachine"
)

// UsersGroup is the group of NAS users (sysusers.d/alpha.conf).
const UsersGroup = "alpha-users"

// NASGroups are the groups whose human members may use the shares:
// ordinary NAS users and administrators.
var NASGroups = []string{UsersGroup, "wheel", "alpha-admin"}

// Settings are what the admin UI can change. The zero value is the default:
// no guest access, Time Machine on.
type Settings struct {
	// MediaGuestRead lets anyone on the LAN read Media without a password
	// (TVs that cannot log in). Never write.
	MediaGuestRead bool `json:"media_guest_read"`
	// TimeMachineOff hides the TimeMachine share.
	TimeMachineOff bool `json:"time_machine_off,omitempty"`
}

// TimeMachine reports whether the TimeMachine share is on.
func (s Settings) TimeMachine() bool { return !s.TimeMachineOff }

// Share describes one share for the API.
type Share struct {
	Name    string `json:"name"`
	Comment string `json:"comment"`
	Path    string `json:"path"`
	// Guest: readable without a password.
	Guest bool `json:"guest"`
}

// Shares lists the shares s renders.
func Shares(s Settings) []Share {
	out := []Share{
		{Name: "Media", Comment: "Медиатека", Path: MediaDir, Guest: s.MediaGuestRead},
		{Name: "Users", Comment: "Личные папки", Path: UsersDir},
	}
	if s.TimeMachine() {
		out = append(out, Share{Name: "TimeMachine", Comment: "Time Machine", Path: TimeMachDir})
	}
	return out
}

func validUsers() string {
	parts := make([]string, len(NASGroups))
	for i, g := range NASGroups {
		parts[i] = "@" + g
	}
	return strings.Join(parts, " ")
}

// Render returns the include file for s.
func Render(s Settings) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# SPDX-License-Identifier: MPL-2.0")
	w("# Generated by alpha-admin-priv (Kinolune OS, DIST-018). Do not edit:")
	w("# it is rewritten at every boot and when the sharing settings change.")
	w("# Settings: %s", SettingsPath)
	w("")
	w("# [global], continued")
	if s.MediaGuestRead {
		w("    map to guest = Bad User")
		w("    restrict anonymous = 0")
		w("    guest account = nobody")
	} else {
		w("    map to guest = Never")
		w("    restrict anonymous = 2")
	}
	w("")
	w("[Media]")
	w("    comment = Медиатека")
	w("    path = %s", MediaDir)
	w("    browseable = yes")
	w("    read only = no")
	if s.MediaGuestRead {
		w("    guest ok = yes")
		w("    valid users = %s nobody", validUsers())
		w("    read list = nobody")
	} else {
		w("    guest ok = no")
		w("    valid users = %s", validUsers())
	}
	w("    force group = %s", UsersGroup)
	w("    create mask = 0664")
	w("    force create mode = 0664")
	w("    directory mask = 2775")
	w("    force directory mode = 2775")
	w("")
	w("[Users]")
	w("    comment = Личные папки")
	w("    path = %s", UsersDir)
	w("    browseable = yes")
	w("    read only = no")
	w("    guest ok = no")
	w("    valid users = %s", validUsers())
	w("    hide unreadable = yes")
	w("    create mask = 0600")
	w("    directory mask = 0700")
	if s.TimeMachine() {
		w("")
		w("[TimeMachine]")
		w("    comment = Time Machine")
		w("    path = %s/%%U", TimeMachDir)
		w("    browseable = yes")
		w("    read only = no")
		w("    guest ok = no")
		w("    valid users = %s", validUsers())
		w("    fruit:time machine = yes")
		w("    create mask = 0600")
		w("    directory mask = 0700")
	}
	return b.String()
}

// LoadSettings reads the settings file; a missing file gives the defaults.
func LoadSettings(path string) (Settings, error) {
	var s Settings
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return s, nil
	}
	if err != nil {
		return s, err
	}
	if err := json.Unmarshal(b, &s); err != nil {
		return Settings{}, fmt.Errorf("%s: %w", path, err)
	}
	return s, nil
}

// SaveSettings writes the settings file atomically (0644: no secrets).
func SaveSettings(path string, s Settings) error {
	b, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return err
	}
	return WriteAtomic(path, append(b, '\n'), 0o644)
}

// WriteAtomic writes data to path through a temporary file and rename.
func WriteAtomic(path string, data []byte, perm os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(perm); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
